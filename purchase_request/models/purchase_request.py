# -*- coding: utf-8 -*-
from collections import defaultdict

from odoo import _, api, fields, models
from odoo.exceptions import UserError


class PurchaseRequest(models.Model):
    _name = 'purchase.request'
    _description = 'Purchase Request'
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _order = 'create_date desc, id desc'

    name = fields.Char(
        string='Request Reference',
        required=True,
        copy=False,
        readonly=True,
        index='trigram',
        default=lambda self: _('New'),
        help="Unique reference of the purchase request, generated by a sequence.")
    state = fields.Selection(
        selection=[
            ('draft', 'Draft'),
            ('confirmed', 'Confirmed'),
        ],
        string='Status',
        required=True,
        default='draft',
        copy=False,
        tracking=True,
        index=True,
    )
    analytic_account_id = fields.Many2one(
        comodel_name='account.analytic.account',
        string='Analytic Account',
        help="Propagated to the lines of the purchase orders generated from this request.")
    requested_by = fields.Many2one(
        comodel_name='res.users',
        string='Requested By',
        default=lambda self: self.env.user,
        copy=False,
    )
    requested_on = fields.Date(
        string='Requested On',
        default=fields.Date.context_today,
        copy=False,
    )
    line_ids = fields.One2many(
        comodel_name='purchase.request.line',
        inverse_name='request_id',
        string='Products',
        copy=True,
    )
    company_id = fields.Many2one(
        comodel_name='res.company',
        string='Company',
        required=True,
        default=lambda self: self.env.company,
    )
    purchase_order_ids = fields.One2many(
        comodel_name='purchase.order',
        inverse_name='purchase_request_id',
        string='Purchase Orders',
    )
    po_count = fields.Integer(
        string='Purchase Order Count',
        compute='_compute_po_count',
    )

    # ------------------------------------------------------------------
    # CRUD overrides
    # ------------------------------------------------------------------

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get('name') or vals['name'] == _('New'):
                vals['name'] = self.env['ir.sequence'].next_by_code('purchase.request') or _('New')
        return super().create(vals_list)

    def write(self, vals):
        # A confirmed request is locked: only the state itself may change,
        # which is what the "Reset to Draft" action uses.
        if not self.env.su and set(vals) - {'state'}:
            for request in self:
                if request.state == 'confirmed':
                    raise UserError(_(
                        "Purchase request %s is confirmed and can no longer be"
                        " modified. Reset it to draft first.", request.name))
        return super().write(vals)

    def unlink(self):
        if not self.env.su:
            for request in self:
                if request.state == 'confirmed':
                    raise UserError(_(
                        "You cannot delete the confirmed purchase request %s."
                        " Reset it to draft first.", request.name))
        return super().unlink()

    # ------------------------------------------------------------------
    # Compute methods
    # ------------------------------------------------------------------

    @api.depends('purchase_order_ids')
    def _compute_po_count(self):
        groups = self.env['purchase.order']._read_group(
            [('purchase_request_id', 'in', self.ids)],
            ['purchase_request_id'],
            ['__count'],
        )
        counts = {request.id: count for request, count in groups}
        for request in self:
            request.po_count = counts.get(request.id, 0)

    # ------------------------------------------------------------------
    # Action methods
    # ------------------------------------------------------------------

    def action_confirm(self):
        for request in self:
            request._check_before_confirm()
            request._create_purchase_orders()
            request.state = 'confirmed'
        return True

    def action_draft(self):
        self.write({'state': 'draft'})
        return True

    def action_view_purchase_orders(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Purchase Orders'),
            'res_model': 'purchase.order',
            'view_mode': 'list,form',
            'domain': [('purchase_request_id', '=', self.id)],
            'context': {
                'default_purchase_request_id': self.id,
                'default_origin': self.name,
            },
        }

    # ------------------------------------------------------------------
    # Business logic
    # ------------------------------------------------------------------

    def _check_before_confirm(self):
        """Validate the request before generating the RFQs."""
        self.ensure_one()
        if not self.line_ids:
            raise UserError(_(
                "You must add at least one product line before confirming"
                " purchase request %s.", self.name))
        for index, line in enumerate(self.line_ids, start=1):
            if not line.product_id:
                raise UserError(_("Line %s: a product is required.", index))
            if not line.vendor_id:
                raise UserError(_(
                    "Line %s (%s): a vendor is required.",
                    index, line.product_id.display_name))
            if not line.product_uom_id:
                raise UserError(_(
                    "Line %s (%s): a unit of measure is required.",
                    index, line.product_id.display_name))
            if line.quantity <= 0:
                raise UserError(_(
                    "Line %s (%s): the quantity must be strictly positive.",
                    index, line.product_id.display_name))

    def _create_purchase_orders(self):
        """Create one draft RFQ per vendor, grouping the lines by vendor.

        Everything runs in a single database transaction: if anything fails,
        the rollback guarantees that no partially created RFQs are left
        behind and that the request is never confirmed by mistake.
        """
        self.ensure_one()
        lines_by_vendor = defaultdict(lambda: self.env['purchase.request.line'])
        for line in self.line_ids:
            lines_by_vendor[line.vendor_id] |= line

        purchase_orders = self.env['purchase.order']
        for vendor, lines in lines_by_vendor.items():
            purchase_order = self.env['purchase.order'].create({
                'partner_id': vendor.id,
                'company_id': self.company_id.id,
                'origin': self.name,
                'purchase_request_id': self.id,
            })
            self.env['purchase.order.line'].create([
                self._prepare_rfq_line_vals(purchase_order, line)
                for line in lines
            ])
            purchase_orders |= purchase_order
        return purchase_orders

    def _prepare_rfq_line_vals(self, purchase_order, request_line):
        """Values used to create one RFQ line.

        Only the product, the quantity and the UoM are passed: the Odoo core
        override of purchase.order.line.create() deduces the description, the
        vendor price, the taxes and the expected receipt date itself through
        _prepare_add_missing_fields(), i.e. Odoo's standard purchase logic.
        """
        vals = {
            'order_id': purchase_order.id,
            'product_id': request_line.product_id.id,
            'product_qty': request_line.quantity,
            'product_uom': request_line.product_uom_id.id,
        }
        account = self.analytic_account_id
        if account and (not account.company_id or account.company_id == purchase_order.company_id):
            vals['analytic_distribution'] = {str(account.id): 100}
        return vals